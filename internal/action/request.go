package action

import (
	"bytes"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"path"
	"strings"
	"unicode/utf8"
)

const (
	maxArgumentsBytes = 64 * 1024
	requestHashDomain = "engageguard/request-hash/v1\x00"
)

// ActionCapabilityRequest is an untrusted capability selector. EngageGuard
// resolves the authoritative version and contract digest before authorization.
type ActionCapabilityRequest struct {
	ID      string `json:"id"`
	Version string `json:"version"`
}

// ActionRequest is caller intent only. Authentication, operation identity,
// policy, tool binding and executor audience are deliberately absent.
type ActionRequest struct {
	SchemaVersion string                  `json:"schema_version"`
	AgentID       string                  `json:"agent_id"`
	RunID         string                  `json:"run_id"`
	DecisionID    string                  `json:"decision_id"`
	PlanID        string                  `json:"plan_id"`
	PlanHash      string                  `json:"plan_hash"`
	StepID        string                  `json:"step_id"`
	Capability    ActionCapabilityRequest `json:"capability"`
	ResourceRef   string                  `json:"resource_ref"`
	Arguments     json.RawMessage         `json:"arguments"`
}

// AuthenticatedContext is populated by the authentication middleware, never
// copied from ActionRequest JSON.
type AuthenticatedContext struct {
	TenantID   string `json:"tenant_id"`
	SubjectID  string `json:"subject_id"`
	ActorID    string `json:"actor_id"`
	WorkloadID string `json:"workload_id"`
}

// ActionCapabilityRef is resolved by EngageGuard from its trusted capability
// registry and includes the immutable contract digest.
type ActionCapabilityRef struct {
	ID             string `json:"id"`
	Version        string `json:"version"`
	ContractSHA256 string `json:"contract_sha256"`
}

// CanonicalAction is the trusted, fully resolved action used for authorization,
// human approval and Permit binding. Identity and policy values are derived or
// re-resolved by EngageGuard; OperationID is generated by EngageGuard.
type CanonicalAction struct {
	SchemaVersion     string              `json:"schema_version"`
	TenantID          string              `json:"tenant_id"`
	SubjectID         string              `json:"subject_id"`
	ActorID           string              `json:"actor_id"`
	WorkloadID        string              `json:"workload_id"`
	AgentID           string              `json:"agent_id"`
	RunID             string              `json:"run_id"`
	DecisionID        string              `json:"decision_id"`
	PlanID            string              `json:"plan_id"`
	PlanHash          string              `json:"plan_hash"`
	StepID            string              `json:"step_id"`
	OperationID       string              `json:"operation_id"`
	Capability        ActionCapabilityRef `json:"capability"`
	ResourceRef       string              `json:"resource_ref"`
	Arguments         json.RawMessage     `json:"arguments"`
	ToolBindingDigest string              `json:"tool_binding_digest"`
	PolicyVersion     string              `json:"policy_version"`
	Audience          string              `json:"audience"`
}

func validActionField(value string) bool {
	return value != "" && len(value) <= 512 && utf8.ValidString(value) && strings.TrimSpace(value) == value &&
		!strings.ContainsAny(value, "\x00\r\n\t ")
}

func validSHA256(value string) bool {
	if len(value) != 64 || value != strings.ToLower(value) {
		return false
	}
	decoded, err := hex.DecodeString(value)
	return err == nil && len(decoded) == sha256.Size
}

// ValidateIdempotencyKey validates the stable caller-generated HTTP header.
// The key is an index, not part of RequestHash.
func ValidateIdempotencyKey(key string) error {
	if len(key) == 0 || len(key) > 128 {
		return errors.New("idempotency key must contain 1 to 128 visible ASCII bytes")
	}
	for i := 0; i < len(key); i++ {
		if key[i] < 0x21 || key[i] > 0x7e {
			return errors.New("idempotency key must contain visible ASCII without whitespace")
		}
	}
	return nil
}

// DecodeActionRequest performs strict boundary decoding: duplicate JSON keys,
// unknown Guard-owned fields, trailing values and invalid field constraints are rejected.
func DecodeActionRequest(raw []byte) (ActionRequest, error) {
	if len(raw) == 0 || len(raw) > maxCanonicalJSONBytes {
		return ActionRequest{}, errors.New("ActionRequest body is empty or oversized")
	}
	if _, err := canonicalJSONObject(raw); err != nil {
		return ActionRequest{}, fmt.Errorf("invalid ActionRequest JSON: %w", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var request ActionRequest
	if err := decoder.Decode(&request); err != nil {
		return ActionRequest{}, fmt.Errorf("decode ActionRequest: %w", err)
	}
	if err := request.Validate(); err != nil {
		return ActionRequest{}, err
	}
	canonicalArguments, err := canonicalJSONObject(request.Arguments)
	if err != nil {
		return ActionRequest{}, fmt.Errorf("canonicalize ActionRequest arguments: %w", err)
	}
	request.Arguments = canonicalArguments
	return request, nil
}

func (a ActionRequest) Validate() error {
	for _, value := range []string{
		a.SchemaVersion, a.AgentID, a.RunID, a.DecisionID, a.PlanID,
		a.StepID, a.ResourceRef,
	} {
		if !validActionField(value) {
			return errors.New("invalid ActionRequest field")
		}
	}
	if a.SchemaVersion != "action-request.v1" || !validSHA256(a.PlanHash) ||
		!validActionField(a.Capability.ID) || !validActionField(a.Capability.Version) {
		return errors.New("invalid ActionRequest schema, plan hash or capability reference")
	}
	if len(a.Arguments) == 0 || len(a.Arguments) > maxArgumentsBytes {
		return errors.New("ActionRequest arguments missing or oversized")
	}
	_, err := canonicalJSONObject(a.Arguments)
	if err != nil {
		return fmt.Errorf("invalid ActionRequest arguments: %w", err)
	}
	return nil
}

func (c AuthenticatedContext) Validate() error {
	for _, value := range []string{c.TenantID, c.SubjectID, c.ActorID, c.WorkloadID} {
		if !validActionField(value) {
			return errors.New("invalid authenticated identity context")
		}
	}
	return nil
}

func (a CanonicalAction) Validate() error {
	for _, value := range []string{
		a.SchemaVersion, a.TenantID, a.SubjectID, a.ActorID, a.WorkloadID,
		a.AgentID, a.RunID, a.DecisionID, a.PlanID, a.StepID, a.OperationID,
		a.ResourceRef, a.PolicyVersion, a.Audience,
	} {
		if !validActionField(value) {
			return errors.New("invalid CanonicalAction identity or binding field")
		}
	}
	if a.SchemaVersion != "canonical-action.v1" || !validSHA256(a.PlanHash) ||
		!validActionField(a.Capability.ID) || !validActionField(a.Capability.Version) ||
		!validSHA256(a.Capability.ContractSHA256) || !validSHA256(a.ToolBindingDigest) {
		return errors.New("invalid CanonicalAction schema or resolved binding")
	}
	if len(a.Arguments) == 0 || len(a.Arguments) > maxArgumentsBytes {
		return errors.New("CanonicalAction arguments missing or oversized")
	}
	canonical, err := canonicalJSONObject(a.Arguments)
	if err != nil {
		return fmt.Errorf("invalid CanonicalAction arguments: %w", err)
	}
	if a.Capability.ID == "workspace.write" {
		if err := validateWorkspaceWriteArguments(canonical); err != nil {
			return err
		}
	}
	return nil
}

// RequestHash identifies one logical submission under authenticated identity.
// It excludes Idempotency-Key and server-generated operation_id.
func RequestHash(request ActionRequest, authenticated AuthenticatedContext) (string, error) {
	if err := request.Validate(); err != nil {
		return "", err
	}
	if err := authenticated.Validate(); err != nil {
		return "", err
	}
	preimage := struct {
		AuthenticatedContext AuthenticatedContext `json:"authenticated_context"`
		Request              ActionRequest        `json:"request"`
	}{AuthenticatedContext: authenticated, Request: request}
	raw, err := json.Marshal(preimage)
	if err != nil {
		return "", err
	}
	canonical, err := canonicalJSONObject(raw)
	if err != nil {
		return "", err
	}
	return digestWithDomain(requestHashDomain, canonical), nil
}

// ActionHash identifies the exact trusted, resolved action. It is computed
// after authentication, capability and ToolBinding resolution, and policy evaluation.
func ActionHash(action CanonicalAction) (string, error) {
	if err := action.Validate(); err != nil {
		return "", err
	}
	raw, err := json.Marshal(action)
	if err != nil {
		return "", err
	}
	canonical, err := canonicalJSONObject(raw)
	if err != nil {
		return "", err
	}
	return digestWithDomain(actionHashDomain, canonical), nil
}

func ApprovalMatchesActionHash(approvedHash string, action CanonicalAction) bool {
	current, err := ActionHash(action)
	if err != nil || !validSHA256(approvedHash) {
		return false
	}
	expected, _ := hex.DecodeString(approvedHash)
	actual, _ := hex.DecodeString(current)
	return subtle.ConstantTimeCompare(expected, actual) == 1
}

func digestWithDomain(domain string, canonical []byte) string {
	preimage := make([]byte, 0, len(domain)+len(canonical))
	preimage = append(preimage, domain...)
	preimage = append(preimage, canonical...)
	digest := sha256.Sum256(preimage)
	return hex.EncodeToString(digest[:])
}

func validateWorkspaceWriteArguments(canonical []byte) error {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(canonical, &fields); err != nil {
		return fmt.Errorf("invalid workspace.write arguments: %w", err)
	}
	if len(fields) != 2 || fields["path"] == nil || fields["content_sha256"] == nil {
		return errors.New("workspace.write arguments must contain exactly path and content_sha256")
	}
	var relativePath, contentSHA256 string
	if err := json.Unmarshal(fields["path"], &relativePath); err != nil {
		return errors.New("workspace.write path must be a string")
	}
	if err := json.Unmarshal(fields["content_sha256"], &contentSHA256); err != nil {
		return errors.New("workspace.write content_sha256 must be a string")
	}
	if !validWorkspaceRelativePath(relativePath) {
		return errors.New("workspace.write path must be a canonical relative path without traversal")
	}
	if !validSHA256(contentSHA256) {
		return errors.New("workspace.write content_sha256 must be a lowercase SHA-256 digest")
	}
	return nil
}

func validWorkspaceRelativePath(value string) bool {
	if value == "" || len(value) > 4096 || !utf8.ValidString(value) ||
		strings.HasPrefix(value, "/") || hasWindowsDrivePrefix(value) ||
		strings.ContainsAny(value, "\\\x00") || path.Clean(value) != value || value == "." {
		return false
	}
	for _, segment := range strings.Split(value, "/") {
		if segment == ".." || segment == "." || segment == "" {
			return false
		}
	}
	return true
}

func hasWindowsDrivePrefix(value string) bool {
	if len(value) < 2 || value[1] != ':' {
		return false
	}
	letter := value[0]
	return (letter >= 'a' && letter <= 'z') || (letter >= 'A' && letter <= 'Z')
}
